// PARTS自体は「Excelの80部位」のままにしておく(ドロップ抽選や図鑑の母数がずれないように)。
export function getPart(id: string): PartDef | undefined {
  return PARTS.find((p) => p.id === id) ?? getFusionPart(id);
}
